"""Generate benchmark/comparison fixtures for QuickIK, from flygym + real mocap data.

Produces two files under `benchmark/assets/`:

  - `neuromechfly_ypr_legs.json`: the kinematic tree (re-exported here so the
    fixtures and the body plan always come from the same model), via
    `../flygym/scripts/export_model_for_flyik.py`.
  - `fixtures.json`: sample frames for the Rust benchmark to replay, of three
    kinds:

    - "synthetic" frames: keypoint targets generated by running this exact
      model's own forward kinematics on the *real* recorded ground-truth
      joint angles (ground truth reachable-by-construction). Used to check
      QuickIK's solver actually recovers the known angles, not just fit some
      residual.
    - "real" frames: real (noisy) mocap keypoints from a recorded fly
      (`flygym_demo`'s bundled Spotlight clip), rigidly aligned into this
      model's own frame convention (see `_kabsch_align`), plus flygym.ik's own
      solved reconstruction on the same targets, for a cross-solver check.
      Sparsely sampled (every 30th recorded frame, ~91ms apart) since this is
      meant to cover a diverse spread of poses for the correctness check, not
      to simulate continuous tracking -- do not use this for a warm-start
      *performance* benchmark, it understates how warm "warm start" is in
      real continuous use (see `native_rate_frames` instead).
    - "native rate" frames: a *contiguous* run of consecutive recorded frames
      (no gaps), for benchmarking `solve_frame`'s warm start under the
      frame-to-frame motion an actual continuous tracking pipeline would see.
      No flygym.ik reconstruction (this is a performance-only fixture, not a
      correctness one).

Run with flygym's own venv:

    uv run python benchmark/scripts/generate_fixtures.py

(from the QuickIK repo root, assuming ../flygym is a sibling checkout).
"""

import json
import subprocess
import sys
from pathlib import Path

import numpy as np
import mujoco as mj

FLYGYM_ROOT = Path(__file__).resolve().parents[3] / "flygym"
BENCHMARK_DIR = Path(__file__).resolve().parents[1]
ASSETS_DIR = BENCHMARK_DIR / "assets"
BODYPLAN_NAME = "neuromechfly_ypr_legs"

sys.path.insert(0, str(FLYGYM_ROOT / "src"))

JOINT_KEYS = ["thorax_coxa", "coxa_trochanterfemur", "trochanterfemur_tibia", "tibia_tarsus"]
LEGS = ["lf", "lm", "lh", "rf", "rm", "rh"]

SYNTHETIC_FRAMES = [50, 120, 200, 280, 350, 420, 490, 560]
REAL_FRAMES = list(range(20, 660, 30))  # ~22 evenly spaced frames
KABSCH_FRAMES = [50, 150, 300, 450, 550]
NATIVE_RATE_START = 100
NATIVE_RATE_LENGTH = 300  # consecutive frames, ~0.91s at this recording's 330 Hz


def export_bodyplan() -> None:
    """(Re-)generate the body plan JSON via flygym's own export script."""
    export_script = FLYGYM_ROOT / "scripts" / "export_model_for_flyik.py"
    subprocess.run([sys.executable, str(export_script)], cwd=ASSETS_DIR, check=True)
    generated = ASSETS_DIR / f"{BODYPLAN_NAME}.json"
    assert generated.exists(), f"expected export script to write {generated}"


def compose_model():
    from flygym.anatomy import AxisOrder, JointPreset, Skeleton
    from flygym.compose import KinematicPosePreset, NeuroMechFly

    fly = NeuroMechFly()
    skeleton = Skeleton(joint_preset=JointPreset.ALL_BIOLOGICAL, axis_order=AxisOrder.YAW_PITCH_ROLL)
    fly.add_joints(skeleton, KinematicPosePreset.NEUTRAL)
    fly.mjcf_root.compiler.fusestatic = False
    mj_model, mj_data = fly.compile()
    return mj_model, mj_data


def build_dof_axis_order(bodyplan: dict) -> dict:
    """joint_key -> list of axis names, in the order the exported JSON's dofs appear."""
    by_name = {j["name"]: j for j in bodyplan["joints"]}
    order = {}
    for jk in JOINT_KEYS:
        node = by_name[f"lf_{jk}"]
        order[jk] = [d["name"].split("-")[-1] for d in node["dofs"]]
    return order


def npz_to_bp_index_map(dofs_per_leg, bp_axis_order):
    """Map npz's flat per-leg dof index -> flat bp/quickik dof index, and back."""
    link_pair_to_key = {
        ("thorax", "coxa"): "thorax_coxa",
        ("coxa", "trochanterfemur"): "coxa_trochanterfemur",
        ("trochanterfemur", "tibia"): "trochanterfemur_tibia",
        ("tibia", "tarsus1"): "tibia_tarsus",
    }
    npz_dof_info = [(link_pair_to_key[(p, c)], axis) for (p, c, axis) in dofs_per_leg]
    bp_flat_order = [(jk, axis) for jk in JOINT_KEYS for axis in bp_axis_order[jk]]
    npz_to_bp = [bp_flat_order.index(info) for info in npz_dof_info]
    return npz_to_bp


def npz_angles_to_bp_order(npz_angles_7, npz_to_bp):
    out = [None] * 7
    for npz_idx, bp_idx in enumerate(npz_to_bp):
        out[bp_idx] = float(npz_angles_7[npz_idx])
    return out


def build_qpos_addr_map(mj_model, bodyplan: dict):
    """(leg, joint_key) -> list of qpos addresses, in the exported dof order."""
    by_name = {j["name"]: j for j in bodyplan["joints"]}
    addr = {}
    for leg in LEGS:
        for jk in JOINT_KEYS:
            node = by_name[f"{leg}_{jk}"]
            addrs = []
            for dof in node["dofs"]:
                jid = mj.mj_name2id(mj_model, mj.mjtObj.mjOBJ_JOINT, dof["name"])
                assert jid >= 0, dof["name"]
                addrs.append(int(mj_model.jnt_qposadr[jid]))
            addr[(leg, jk)] = addrs
    return addr


def set_leg_qpos(base_qpos, qpos_addr, gt_bp_angles_per_leg):
    qpos = base_qpos.copy()
    for leg, angles in zip(LEGS, gt_bp_angles_per_leg):
        idx = 0
        for jk in JOINT_KEYS:
            addrs = qpos_addr[(leg, jk)]
            for a in addrs:
                qpos[a] = angles[idx]
                idx += 1
    return qpos


def kabsch_align(src_pts, dst_pts):
    """Rigid (rotation + translation, no scaling) alignment src -> dst."""
    src_mean, dst_mean = src_pts.mean(axis=0), dst_pts.mean(axis=0)
    h = (src_pts - src_mean).T @ (dst_pts - dst_mean)
    u, _, vt = np.linalg.svd(h)
    d = np.sign(np.linalg.det(vt.T @ u.T))
    rot = vt.T @ np.diag([1, 1, d]) @ u.T
    trans = dst_mean - rot @ src_mean
    return rot, trans


def main():
    from flygym.ik import KeypointSet, fit_qpos_to_keypoints
    from flygym_demo.spotlight_data.preprocessing import MotionSnippet

    export_bodyplan()
    bodyplan = json.loads((ASSETS_DIR / f"{BODYPLAN_NAME}.json").read_text())
    joint_names = [j["name"] for j in bodyplan["joints"]]
    assert joint_names[0] == "thorax"
    leg_joint_names = joint_names[1:]  # everything but the root, in bodyplan order

    mj_model, mj_data = compose_model()
    qpos_addr = build_qpos_addr_map(mj_model, bodyplan)
    bp_axis_order = build_dof_axis_order(bodyplan)

    snippet = MotionSnippet()
    assert snippet.legs == LEGS
    npz_to_bp = npz_to_bp_index_map(snippet.dofs_per_leg, bp_axis_order)

    thorax_id = [i for i in range(mj_model.nbody) if mj_model.body(i).name.endswith("thorax")][0]
    mj.mj_kinematics(mj_model, mj_data)
    thorax_world_pos = mj_data.xpos[thorax_id].copy()
    thorax_world_mat = mj_data.xmat[thorax_id].reshape(3, 3).copy()

    triples = [tuple(x) for x in snippet.keypoints]  # matches leg_joint_names order
    keypoints = KeypointSet.from_keypoint_triples(triples, mj_model=mj_model)
    body_ids = keypoints.resolve_body_ids(mj_model)
    local_offsets = keypoints.local_offsets()

    def mj_world_keypoints(qpos):
        mj_data.qpos[:] = qpos
        mj.mj_kinematics(mj_model, mj_data)
        xpos = mj_data.xpos[body_ids]
        xmat = mj_data.xmat[body_ids].reshape(-1, 3, 3)
        return xpos + np.einsum("nij,nj->ni", xmat, local_offsets)

    def ego(world_pts):
        return np.einsum("ij,nj->ni", thorax_world_mat.T, world_pts - thorax_world_pos)

    def gt_bp_angles_for(frame):
        return [
            npz_angles_to_bp_order(snippet.joint_angles[frame, li], npz_to_bp)
            for li in range(6)
        ]

    # ---- Kabsch alignment: mocap-ego frame -> this template's own ego frame ----
    src_pts, dst_pts = [], []
    for frame in KABSCH_FRAMES:
        gt_angles = gt_bp_angles_for(frame)
        qpos_gt = set_leg_qpos(mj_model.key_qpos[0], qpos_addr, gt_angles)
        dst_pts.append(ego(mj_world_keypoints(qpos_gt)))
        src_pts.append(snippet.rawpred_egoxyz[frame])
    rot_align, t_align = kabsch_align(
        np.concatenate(src_pts, axis=0), np.concatenate(dst_pts, axis=0)
    )

    def to_template_ego(raw_ego_pts):
        return (rot_align @ raw_ego_pts.T).T + t_align

    # ---- synthetic frames (bug-hunt: exact reachable targets) ----
    synthetic_frames = []
    for frame in SYNTHETIC_FRAMES:
        gt_angles = gt_bp_angles_for(frame)
        qpos_gt = set_leg_qpos(mj_model.key_qpos[0], qpos_addr, gt_angles)
        target_ego = ego(mj_world_keypoints(qpos_gt))
        synthetic_frames.append(
            {
                "frame": frame,
                "target_ego": target_ego.tolist(),
                "ground_truth_dof_angles_per_leg": gt_angles,
            }
        )

    # ---- real frames (real noisy data, cross-checked against flygym.ik) ----
    real_frames = []
    mj_qpos_warm = mj_model.key_qpos[0].copy()
    for frame in REAL_FRAMES:
        target_ego = to_template_ego(snippet.rawpred_egoxyz[frame])
        target_world = target_ego + thorax_world_pos
        result = fit_qpos_to_keypoints(
            mj_model, mj_data, keypoints, target_world,
            initial_qpos=mj_qpos_warm, max_iters=200, ftol=1e-12,
        )
        mj_qpos_warm = result.qpos.copy()
        flygym_reconstructed_ego = ego(mj_world_keypoints(result.qpos))
        real_frames.append(
            {
                "frame": frame,
                "target_ego": target_ego.tolist(),
                "flygym_ik_reconstructed_ego": flygym_reconstructed_ego.tolist(),
                "flygym_ik_success": bool(result.success),
                "flygym_ik_cost": float(result.cost),
            }
        )

    # ---- native-rate frames (contiguous, for a real warm-start benchmark) ----
    native_rate_frames = [
        {"frame": frame, "target_ego": to_template_ego(snippet.rawpred_egoxyz[frame]).tolist()}
        for frame in range(NATIVE_RATE_START, NATIVE_RATE_START + NATIVE_RATE_LENGTH)
    ]

    fixtures = {
        "metadata": {
            "bodyplan": f"{BODYPLAN_NAME}.json",
            "source_recording": snippet.experiment_trial,
            "note": (
                "target_ego/flygym_ik_reconstructed_ego list one [x,y,z] per leg "
                "joint, in the same order as this bodyplan's joints[1:] (i.e. "
                "excluding the free-floating 'thorax' root, which has no mocap "
                "keypoint of its own -- feed it Missing)."
            ),
        },
        "leg_joint_names": leg_joint_names,
        "synthetic_frames": synthetic_frames,
        "real_frames": real_frames,
        "native_rate_frames": native_rate_frames,
    }
    (ASSETS_DIR / "fixtures.json").write_text(json.dumps(fixtures))
    print(
        f"Wrote {len(synthetic_frames)} synthetic + {len(real_frames)} real + "
        f"{len(native_rate_frames)} native-rate frames to {ASSETS_DIR / 'fixtures.json'}"
    )


if __name__ == "__main__":
    main()
